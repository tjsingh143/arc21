-- Give the ledger a true apply order.
--
-- FOUND BY ATTACK. Racing concurrent buy-ins against the live stack produced a
-- ledger that cannot be replayed:
--
--   created_at                      delta   balance_after   reason
--   2026-08-15 23:21:15.613007+00   10000   10000           initial_grant
--   2026-08-15 23:21:15.633520+00   -2000    6000           table_buy_in
--   2026-08-15 23:21:15.633522+00   -2000    8000           table_buy_in
--
-- Ordered by created_at that reads 10000 -> 6000 -> 8000, which is not a valid
-- chain. No chips were lost: every balance_after is correct for the order the
-- rows were actually applied in, and the wallet equals the sum of its deltas.
-- The defect is in the audit trail, not the money.
--
-- The cause is that `created_at default now()` records TRANSACTION START, while
-- apply_wallet_delta serialises on `select ... for update`. A transaction that
-- starts first can acquire the wallet lock second, so created_at inverts under
-- contention. `id` is a random uuid and orders nothing. The table therefore had
-- no column recording the order its rows were applied in — and the index used
-- for reconciliation, (user_id, created_at desc), sorted by the wrong one.
--
-- An append-only ledger whose entries cannot be put back in order is a weak
-- audit trail: any statement, reconciliation or dispute view built on it would
-- render a history that never happened.
--
-- `seq` is assigned by the sequence at INSERT, which happens after the wallet
-- lock is held, so it is the lock-acquisition order — the real one. Sequence
-- allocation is non-transactional, so a rolled-back command may leave a gap.
-- Gaps are expected and harmless; order is what this guarantees, not density.

alter table public.wallet_ledger
  add column if not exists seq bigint generated by default as identity;

comment on column public.wallet_ledger.seq is
  'Monotonic apply order. Assigned at INSERT, under the wallet lock, so it '
  'reflects the order entries were actually applied. Order the ledger by this '
  'and never by created_at, which is transaction-start time and inverts under '
  'concurrency. Gaps are normal (a rolled-back command consumes a value).';

comment on column public.wallet_ledger.created_at is
  'Transaction START time. Correct for "roughly when", wrong for ordering — '
  'see seq.';

-- Existing rows were backfilled in an arbitrary order by the ALTER above; only
-- rows written from here on carry a meaningful seq. This is stated rather than
-- papered over, and is acceptable because no production data exists yet.

create unique index if not exists wallet_ledger_seq_key
  on public.wallet_ledger (seq);

-- The index reconciliation should actually use.
create index if not exists wallet_ledger_user_seq_idx
  on public.wallet_ledger (user_id, seq);
