-- -----------------------------------------------------------------------------
-- Catalogue data has MOVED to migrations
--
-- The ruleset, the cosmetics and the career map are now written by
-- `20260823110000_catalogue_ships_in_migrations.sql` and
-- `20260823120000_career_catalogue.sql`. They are not repeated here.
--
-- The reason is not tidiness. This file runs on `supabase db reset` and NOT on
-- `supabase db push`, so catalogue data that lives only here does not exist in
-- a deployed project — and with no `rulesets` row, no session of any kind can
-- be created. Anything a deployed database needs in order to function belongs
-- in a migration.
--
-- This file is now deliberately empty of catalogue rows. It is kept because
-- `supabase db reset` expects it and because local-only fixtures, if any are
-- ever needed, belong here and nowhere else.
